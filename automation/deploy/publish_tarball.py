#!/usr/bin/env python3
"""Publish the generated site by uploading one archive and extracting it.

    python3 automation/deploy/publish_tarball.py --verify
    python3 automation/deploy/publish_tarball.py --dry-run
    python3 automation/deploy/publish_tarball.py

The host throttles SFTP to roughly one request per second, so uploading ~1,100
pages file-by-file takes about twenty minutes and cannot finish inside the
automation's wall clock. The host does allow non-interactive shell commands
over the same SSH session, so the whole site is shipped as a single tarball and
unpacked with one `tar -xzf` on the far side. That turns a twenty-minute
publish into a few seconds.

--verify  connect and report what is at the remote path. Changes nothing.
--dry-run package and report sizes, upload nothing.
(default) package, upload, extract, and prune orphaned managed pages.

Refuses to publish to a path that does not look like a web root, so a wrong
secret cannot scatter files across the server. Never prints a credential.
"""

import argparse
import json
import os
import posixpath
import subprocess
import sys
import tarfile
import tempfile
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / "automation" / "mvp" / "site"

SECRETS = {
    "TOOLSUMMARY_SFTP_HOST": "VHOST",
    "TOOLSUMMARY_SFTP_USER": "VUSER",
    "TOOLSUMMARY_SFTP_PORT": "VPORT",
    "TOOLSUMMARY_SFTP_PATH": "VREMOTE",
    "Remote_Path": "VREMOTE_FALLBACK",
}

CREDENTIAL_SECRETS = (
    "TOOLSUMMARY_SFTP_PASSWORD",
    "TOOLSUMMARY_SFTP_KEY",
    "TOOLSUMMARY_SFTP_PASS",
)

SAFE_PATH_MARKERS = ("public_html", "htdocs", "httpdocs", "domains/", "/www")

# Only these are ours to replace or prune. Anything else in the web root
# belongs to the owner. .htaccess is generated by the build, so the
# placeholder's noindex version must be overwritten.
MANAGED_FILES = (".htaccess", "index.html", "sitemap.xml", "llms.txt", "robots.txt")
MANAGED_DIRS = ("model", "compare")


def get_secret(name: str) -> str | None:
    """Fetch a named secret, or None if it is not configured.

    Local Agent Canvas sets AGENT_SERVER_URL and serves secrets under
    /api/settings/secrets. A cloud sandbox does not set it and serves them
    under the sandbox-scoped path instead.
    """
    if os.environ.get(name):
        return os.environ[name]

    key = os.environ.get("SESSION_API_KEY") or os.environ.get("OH_SESSION_API_KEYS_0", "")
    if not key:
        return None

    url = os.environ.get("AGENT_SERVER_URL", "").rstrip("/")
    if url:
        endpoint = f"{url}/api/settings/secrets/{name}"
    else:
        api = os.environ.get("OPENHANDS_CLOUD_API_URL", "").rstrip("/")
        sandbox = os.environ.get("SANDBOX_ID", "")
        if not api or not sandbox:
            return None
        endpoint = f"{api}/api/v1/sandboxes/{sandbox}/settings/secrets/{name}"

    req = urllib.request.Request(endpoint, headers={"X-Session-API-Key": key})
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return r.read().decode().rstrip("\r\n")
    except urllib.error.HTTPError:
        return None
    except Exception:
        return None


def resolve(names: dict[str, str]) -> dict[str, str]:
    out = {}
    for secret_name, var in names.items():
        value = os.environ.get(var) or get_secret(secret_name)
        if value:
            out[var] = value
    return out


def resolve_credential() -> tuple[str, str]:
    value = os.environ.get("VSECRET")
    source = "VSECRET" if value else ""
    if not value:
        for secret_name in CREDENTIAL_SECRETS:
            value = os.environ.get(secret_name) or get_secret(secret_name)
            if value:
                source = secret_name
                break
    if not value:
        return "", "missing"
    kind = "key" if value.lstrip().startswith("-----BEGIN") else "password"
    return value, f"{kind} (from {source})"


def looks_like_web_root(path: str) -> bool:
    low = path.lower()
    return any(m in low for m in SAFE_PATH_MARKERS)


def package(site: Path, dest: Path) -> int:
    """Write the site as a gzipped tar with paths relative to the site root.

    Uses deterministic-ish ordering so an unchanged site produces a similar
    archive; the far side extracts in place, so the archive must not contain a
    wrapping directory. A manifest of the managed directories is included so
    the far side can prune pages that dropped out of the build.
    """
    managed = [d for d in MANAGED_DIRS if (site / d).is_dir()]
    with tarfile.open(dest, "w:gz") as tar:
        for path in sorted(site.rglob("*")):
            if path.is_file():
                tar.add(path, arcname=str(path.relative_to(site)))
        manifest = "\n".join(
            str(p.relative_to(site))
            for d in managed for p in sorted((site / d).iterdir()) if p.is_dir()
        ).encode()
        info = tarfile.TarInfo(".ts-manifest")
        info.size = len(manifest)
        info.mode = 0o644
        tar.addfile(info, __import__("io").BytesIO(manifest))
    return dest.stat().st_size


def main() -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--verify", action="store_true")
    g.add_argument("--dry-run", action="store_true")
    ap.add_argument("--allow-any-path", action="store_true")
    a = ap.parse_args()

    mode = "verify" if a.verify else "dry-run" if a.dry_run else "publish"

    cfg = resolve(SECRETS)
    remote = cfg.get("VREMOTE") or cfg.get("VREMOTE_FALLBACK")
    secret, auth = resolve_credential()

    missing = [n for n in ("VHOST", "VUSER") if not cfg.get(n)]
    if not remote:
        missing.append("TOOLSUMMARY_SFTP_PATH (or Remote_Path)")
    if not secret:
        missing.append("TOOLSUMMARY_SFTP_PASSWORD or TOOLSUMMARY_SFTP_KEY")
    if missing:
        print("missing configuration: " + ", ".join(missing))
        return 2

    if "VREMOTE" in cfg:
        print("remote path source: TOOLSUMMARY_SFTP_PATH")
    else:
        print("remote path source: Remote_Path (TOOLSUMMARY_SFTP_PATH is unset)")

    if not looks_like_web_root(remote) and not a.allow_any_path:
        print(f"refusing: remote path does not look like a web root "
              f"(length {len(remote)}). Expected one of {SAFE_PATH_MARKERS}. "
              f"Pass --allow-any-path to override.")
        return 2

    if mode != "verify" and not SITE.is_dir():
        print(f"refusing: no built site at {SITE}. Run build_pages.py first.")
        return 2

    try:
        import paramiko  # noqa: F401
    except ImportError:
        subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                        "--no-warn-script-location", "--disable-pip-version-check",
                        "paramiko"],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    import paramiko

    remote = remote.rstrip("/")
    client = paramiko.SSHClient()
    client.set_missing_host_key_policy(paramiko.AutoAddPolicy())
    kwargs = dict(hostname=cfg["VHOST"], port=int(cfg.get("VPORT") or 22),
                  username=cfg["VUSER"], timeout=30, banner_timeout=30,
                  auth_timeout=30, allow_agent=False, look_for_keys=False)
    if auth.startswith("key"):
        kwargs["pkey"] = paramiko.RSAKey.from_private_key(__import__("io").StringIO(secret))
    else:
        kwargs["password"] = secret

    try:
        client.connect(**kwargs)
    except paramiko.AuthenticationException:
        print("RESULT: AUTH FAILED - wrong user or password, or SSH access not enabled")
        return 1
    except Exception as e:
        print(f"RESULT: FAILED - {type(e).__name__}: {e}")
        return 1

    print(f"mode: {mode} | auth: {auth} | port: {cfg.get('VPORT', '22')}")

    def run(cmd: str, timeout: int = 600):
        _in, out, err = client.exec_command(cmd, timeout=timeout)
        return (out.read().decode(errors="replace"),
                err.read().decode(errors="replace"),
                out.channel.recv_exit_status())

    try:
        if mode == "verify":
            stdout, stderr, rc = run(
                f"cd {remote} 2>/dev/null && echo OK && ls -1 | head -20 || echo NOPE")
            if "OK" not in stdout:
                print(f"RESULT: FAILED - remote path not reachable: {stdout.strip()[:200]}")
                return 1
            count, _, _ = run(f"cd {remote} && find . -type f | wc -l")
            print(f"RESULT: auth OK | remote reachable | files: {count.strip()}")
            return 0

        with tempfile.TemporaryDirectory() as td:
            tar_path = Path(td) / "site.tar.gz"
            size = package(SITE, tar_path)
            local_files = sum(1 for p in SITE.rglob("*") if p.is_file())
            print(f"packaged {local_files} files -> {size} bytes")

            if mode == "dry-run":
                print(f"RESULT: would upload {size} bytes and extract {local_files} files "
                      f"into the remote root")
                return 0

            sftp = client.open_sftp()
            sftp.get_channel().settimeout(300)
            staging = posixpath.join(remote, ".ts-site.tar.gz")
            sftp.put(str(tar_path), staging)
            sftp.close()

            # Extract in place, then remove the staging archive. `--no-same-owner`
            # avoids a chown failure on a shared host. The manifest lists the
            # page directories that belong to the current build; any other
            # directory under a managed tree is a leftover and is removed, while
            # owner files elsewhere in the web root are never touched.
            managed_dirs = " ".join(MANAGED_DIRS)
            cmd = (
                f"cd {remote} && "
                f"tar --no-same-owner -xzf .ts-site.tar.gz && rm -f .ts-site.tar.gz && "
                f"echo EXTRACTED && "
                f"sort -u .ts-manifest > .ts-manifest.sorted && "
                f"for d in {managed_dirs}; do "
                f"  [ -d \"$d\" ] || continue; "
                f"  for sub in \"$d\"/*/; do "
                f"    [ -d \"$sub\" ] || continue; "
                f"    rel=\"${{sub%/}}\"; "
                f"    if ! grep -qxF \"$rel\" .ts-manifest.sorted; then "
                f"      rm -rf \"$sub\"; echo \"pruned $rel\"; "
                f"    fi; "
                f"  done; "
                f"done; "
                f"rm -f .ts-manifest .ts-manifest.sorted"
            )
            stdout, stderr, rc = run(cmd)
            if rc != 0 or "EXTRACTED" not in stdout:
                print(f"RESULT: FAILED - extract rc={rc}: {(stderr or stdout).strip()[:300]}")
                return 1

            model, _, _ = run(f"cd {remote} && find model -name index.html | wc -l")
            comp, _, _ = run(f"cd {remote} && find compare -name index.html | wc -l")
            print(f"RESULT: uploaded and extracted {local_files} files "
                  f"(model pages: {model.strip()}, comparison pages: {comp.strip()})")
            return 0
    finally:
        client.close()


if __name__ == "__main__":
    raise SystemExit(main())
